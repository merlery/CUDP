"""Chapter 5 outputs: make_figures.py / make_tables.py / gen_ch5.py run on the committed summaries and recorded
runs, and a missing cell is reported by name."""
import importlib.util
import shutil
import subprocess
import sys
from pathlib import Path

import pandas as pd
import pytest

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "results" / "summary"
REQUIRED = ["adult_final.csv", "bank_final.csv", "mnist_final.csv", "fmnist_final.csv", "attribute_inference.csv",
            "majority_rates.csv"]
CHAPTER_LABELS = ["law", "main", "bank_main", "group", "pilotA", "pilotB", "selection", "selbal", "ablation", "exposure", "local",
                  "mask", "central"]

pytestmark = pytest.mark.skipif(not all((SUMMARY / f).exists() for f in REQUIRED),
                                reason="committed results/summary files are required")


def _load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def test_selection_figure_and_tables_generate(tmp_path):
    _load("paper_common")
    mf = _load("make_figures")
    mt = _load("make_tables")
    assert mf.main(["--out", str(tmp_path / "figures")]) == 0
    assert mt.main(["--out", str(tmp_path / "tables")]) == 0
    assert (tmp_path / "figures" / "fig_selection.pdf").exists()
    for t in ("tab_selection", "tab_selection_bal", "tab_selection_ablation", "tab_selection_exposure"):
        text = (tmp_path / "tables" / f"{t}.tex").read_text()
        assert text.startswith("% generated by scripts/make_tables.py")
        assert "\\toprule" in text and "\\bottomrule" in text


def test_chapter_generator_writes_every_table():
    out = subprocess.run([sys.executable, str(ROOT / "scripts" / "gen_ch5.py")], capture_output=True, text=True, cwd=ROOT)
    assert out.returncode == 0, out.stderr[-2000:]
    tex = (ROOT / "thesis_tex" / "ch5_tables.tex").read_text()
    for lab in CHAPTER_LABELS:
        assert f"\\label{{tab:ch5:{lab}}}" in tex, lab
    for fig in ("pu_ch5.pdf", "selection_ch5.pdf", "mask_ch5.pdf"):
        assert (ROOT / "thesis_tex" / "figures" / fig).exists(), fig


def test_missing_cell_is_named(tmp_path, monkeypatch):
    pc = _load("paper_common")
    copy = tmp_path / "summary"
    shutil.copytree(SUMMARY, copy)
    df = pd.read_csv(copy / "adult_final.csv")
    df = df[~((df.config == "adult_occ_v7_sel_mi_k10") & ((df.eps - 200.0).abs() < 1e-9))]
    df.to_csv(copy / "adult_final.csv", index=False)
    monkeypatch.setattr(pc, "SUMMARY", copy)
    mt = _load("make_tables")
    with pytest.raises(pc.MissingCell, match="adult_occ_v7_sel_mi_k10"):
        mt.main(["--out", str(tmp_path / "tables")])

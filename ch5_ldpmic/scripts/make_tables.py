def tab_cap(out: Path):
    df = load_final("adult")
    att = load_csv("attribute_inference.csv")
    att = att[att.dataset == "adult"]
    rows, cfgs = [], []
    for tag, part, apart in (("occ", "occupation", "group"), ("dir0.5", "Dirichlet(0.5)", "dirichlet")):
        rows.append((r"\midrule" + "\n" if rows else "") + r"\multicolumn{6}{l}{\textit{Adult, " + part + " partition}}")
        for rowlabel, cfg in ((r"exp, no cap", f"adult_{tag}_ldpmic_global"), (r"exp + cap ($p_j \le 1/d$ on sex, race)", f"adult_{tag}_cap_sexrace")):
            cfgs.append(cfg)
            cells = [pm(cell(df, "adult", cfg, e).accuracy_mean, cell(df, "adult", cfg, e).accuracy_std) for e in EPS_GRID]
            rows.append(rowlabel + " & " + " & ".join(cells))
        for rowlabel, cfg in ((r"\quad SNR $\Delta_j/\sigma_j$ of sex/race columns, no cap", f"adult_{tag}_ldpmic_global"),
                              (r"\quad SNR $\Delta_j/\sigma_j$ of sex/race columns, cap", f"adult_{tag}_cap_sexrace")):
            cells = []
            for e in EPS_GRID:
                r = att[(att.partition == apart) & (att.config == cfg) & ((att.eps - e).abs() < 1e-9)]
                if r.empty:
                    raise MissingCell(f"missing SNR cell: dataset=adult, config={cfg}, eps={e}")
                cells.append(f"{r.snr_mean.mean():.4f}")
            rows.append(rowlabel + " & " + " & ".join(cells))
    caption = ("Sensitive-attribute cap (experiment D): final test accuracy of the exp allocation on Adult with and without "
               "capping the shares of the sex and race one-hot columns at $p_{\\max}=1/d$, and the resulting per-column "
               "signal-to-noise ratio $\\Delta_j/\\sigma_j$ of those columns (mean over the 7 columns and over clients; "
               "$\\sigma_j$ per feature is listed in Table~\\ref{tab:sigma_adult}). Seeds: " + seeds_of(df, cfgs) + ".")
    header = r"setting & " + " & ".join(f"$\\varepsilon={fmt_eps(e)}$" for e in EPS_GRID)
    write(out, "tab_cap", table("l" + "r" * len(EPS_GRID), header, rows, caption, "tab:cap", env="table*"))


def tab_exposure(out: Path):
    att = load_csv("attribute_inference.csv")
    att = att[att.dataset == "adult"]
    rows = []
    configs = (("isotropic", "adult_occ_iso"), ("exp allocation", "adult_occ_ldpmic_global"), ("exp allocation + cap", "adult_occ_cap_sexrace"))
    n_seeds = set()
    for apart, part in (("group", "occupation"), ("dirichlet", "Dirichlet(0.5)")):
        for attr in ("sex", "race"):
            sub = att[(att.partition == apart) & (att.attribute == attr)]
            rows.append((r"\midrule" + "\n" if rows else "") + r"\multicolumn{8}{l}{\textit{" + f"{part} partition, attribute {attr}" + "}}")
            for label, cfg in configs:
                cfg = cfg.replace("_occ_", "_dir0.5_") if apart == "dirichlet" else cfg
                cells = []
                maj = raw = None
                for e in EPS_GRID:
                    r = sub[(sub.config == cfg) & ((sub.eps - e).abs() < 1e-9)]
                    if len(r) != 1:
                        raise MissingCell(f"missing attack cell: dataset=adult, config={cfg}, attribute={attr}, eps={e}")
                    r = r.iloc[0]; n_seeds.add(int(r.n_seeds))
                    cells.append(f"{r.accuracy_mean:.3f} ({r.balanced_accuracy_mean:.3f})")
                    maj, raw = r.majority_accuracy_mean, r.raw_balanced_accuracy_mean
                rows.append(label + " & " + " & ".join(cells) + f" & {maj:.3f} & {raw:.3f}")
    caption = ("Attribute inference on released records (experiment E6): accuracy (balanced accuracy in parentheses) of a "
               "logistic-regression attacker trained on the sanitized records of half the clients and evaluated on the other "
               "half, predicting the record's sex or race from its other sanitized coordinates; ``majority'' is the "
               "majority-class accuracy of the evaluation records and ``raw'' the balanced accuracy of the same attacker on "
               "raw (unperturbed) records. Seeds: " + ", ".join(map(str, sorted(n_seeds))) + ".")
    header = r"records from & " + " & ".join(f"$\\varepsilon={fmt_eps(e)}$" for e in EPS_GRID) + " & majority & raw"
    write(out, "tab_exposure", table("l" + "r" * (len(EPS_GRID) + 2), header, rows, caption, "tab:exposure", env="table*"))



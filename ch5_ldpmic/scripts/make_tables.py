def tab_sigma_adult(out: Path, eps: float = 1.0, allocations=("uniform", "exp", "linear", "cap")):
    al = load_csv("adult_allocation.csv")
    al = al[(al.eps - eps).abs() < 1e-9]
    base = al[al.allocation == allocations[0]].sort_values("feature_index")
    if base.empty:
        raise MissingCell(f"missing allocation rows: dataset=adult, method={allocations[0]}, eps={eps}")
    cols = {a: al[al.allocation == a].sort_values("feature_index").set_index("feature_index") for a in allocations}
    for a, c in cols.items():
        if len(c) != len(base):
            raise MissingCell(f"missing allocation rows: dataset=adult, method={a}, eps={eps}")
    rows = []
    for _, r in base.iterrows():
        j = int(r.feature_index)
        cells = [tex(r.feature) + (r" $\dagger$" if r.sensitive else ""), f"{r.delta_j:g}"]
        for a in allocations:
            c = cols[a].loc[j]
            cells += [f"{c.p_mean:.4f}", f"{c.sigma_scaled_mean:.1f}", f"{c.eps_equiv_mean:.3f}"]
        rows.append(" & ".join(cells))
    n = int(base.n_seeds.iloc[0])
    e2 = {a: cols[a].eps2.iloc[0] for a in allocations}
    d2 = cols[allocations[-1]].delta2.iloc[0]
    budgets = ", ".join(f"{ {'uniform': 'uniform', 'exp': 'exp', 'linear': 'linear', 'cap': 'exp + cap'}[a] }: "
                        f"$\\varepsilon_2={e2[a]:g}$" for a in allocations)
    caption = (f"Per-feature allocation on Adult at $\\varepsilon={eps:g}$ (Phase~3 budgets {budgets}; "
               f"$\\delta_2={d2:.0e}$".replace("e-06", r"\times 10^{-6}") + "): public range width $\\Delta_j$, share $p_j$, noise std in scaled units "
               "$\\sigma_j/\\Delta_j$ and the per-feature $\\varepsilon$-equivalent $\\varepsilon_j$ (the budget the "
               "Gaussian mechanism on coordinate $j$ alone would consume at $\\delta_2$; a diagnostic, not part of the "
               "accounting) under uniform (isotropic), exponential, linear and capped shares; $\\dagger$ marks the "
               f"sensitive (sex, race) columns capped at $p_j \\le 1/d$. Means over {n} seeds.")
    header = r"feature & $\Delta_j$ & " + " & ".join(
        f"$p_j$ & $\\sigma_j/\\Delta_j$ & $\\varepsilon_j$" for _ in allocations)
    pre = (r"\multicolumn{2}{c}{} & " + " & ".join(r"\multicolumn{3}{c}{" + {"uniform": "uniform", "exp": "exp", "linear": "linear", "cap": "exp + cap"}[a] + "}" for a in allocations) + r" \\")
    body = table("lr" + "rrr" * len(allocations), pre + "\n" + header, rows, caption, "tab:sigma_adult", longtable=True)
    write(out, "tab_sigma_adult", body)



def tab_main(out: Path):
    rows, notes = [], []
    methods = ("iso", "ldpmic_global", "ldpmic_per_client", "local_dpsgd")
    for ds, meta in DATASETS.items():
        df = load_final(ds)
        pre = meta["prefix"]
        nodp = cell(df, ds, f"{pre}_nodp", None)
        rows.append((r"\midrule" + "\n" if rows else "") + r"\multicolumn{6}{l}{\textit{" + meta["name"]
                    + f" ({meta['partition']}, $T={int(nodp.rounds)}$); no DP: {pm(nodp.accuracy_mean, nodp.accuracy_std)}" + "}}")
        for m in methods:
            cells = []
            for e in EPS_GRID:
                r = cell(df, ds, f"{pre}_{m}", e)
                cells.append(pm(r.accuracy_mean, r.accuracy_std) + (f" ({int(r.n_diverged)}d)" if r.n_diverged > 0 else ""))
            rows.append(METHODS[m]["name"] + " & " + " & ".join(cells))
        notes.append(f"{meta['name']}: {seeds_of(df, [f'{pre}_{m}' for m in methods])} seeds")
    caption = ("Final test accuracy (mean $\\pm$ std over seeds) of each private method at every privacy budget "
               "$\\varepsilon$ ($\\delta = 10^{-5}$); ``$k$d'' marks $k$ seeds whose training diverged (non-finite loss). "
               "Seeds: " + "; ".join(notes) + ".")
    header = r"method & " + " & ".join(f"$\\varepsilon={fmt_eps(e)}$" for e in EPS_GRID)
    write(out, "tab_main", table("l" + "r" * len(EPS_GRID), header, rows, caption, "tab:main", env="table*"))


def _ablation_like(out: Path, name: str, label: str, variants, caption_core: str):
    """variants: list of (row label, config template with {ds}{tag})"""
    rows, notes = [], []
    for ds in ("adult", "bank"):
        df = load_final(ds)
        for tag, part in (("occ", DATASETS[ds]["partition"]), ("dir0.5", "Dirichlet(0.5)")):
            rows.append((r"\midrule" + "\n" if rows else "") + r"\multicolumn{6}{l}{\textit{" + DATASETS[ds]["name"] + f", {part} partition" + "}}")
            cfgs = []
            for rowlabel, tmpl in variants:
                cfg = tmpl.format(ds=ds, tag=tag)
                cfgs.append(cfg)
                cells = []
                for e in EPS_GRID:
                    r = cell(df, ds, cfg, e)
                    cells.append(pm(r.accuracy_mean, r.accuracy_std) + (f" ({int(r.n_diverged)}d)" if r.n_diverged > 0 else ""))
                rows.append(rowlabel + " & " + " & ".join(cells))
            notes.append(f"{DATASETS[ds]['name']}/{part}: {seeds_of(df, cfgs)} seeds")
    caption = caption_core + " ``$k$d'' marks $k$ diverged seeds. Seeds: " + "; ".join(notes) + "."
    header = r"variant & " + " & ".join(f"$\\varepsilon={fmt_eps(e)}$" for e in EPS_GRID)
    write(out, name, table("l" + "r" * len(EPS_GRID), header, rows, caption, label, env="table*"))



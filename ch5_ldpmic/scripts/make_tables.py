"""Generate every paper table (.tex, booktabs) from results/summary/*.csv.

    python scripts/make_tables.py [--out tables]

Cells are "mean $\\pm$ std" over seeds; the number of seeds is stated in
the caption; nothing is bold; the files are written verbatim and never
edited by hand.  A missing required cell raises ``MissingCell`` naming the
(dataset, method, eps).
"""


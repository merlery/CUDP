HEADER = "% generated by scripts/make_tables.py from results/summary/*.csv -- do not edit by hand\n"


def write(out: Path, name: str, body: str) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{name}.tex").write_text(HEADER + body)
    print("wrote", out / f"{name}.tex")


def tex(s: str) -> str:
    return s.replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def table(cols: str, header: str, rows, caption: str, label: str, env: str = "table", longtable: bool = False) -> str:
    if longtable:
        body = [r"\begin{longtable}{" + cols + "}", r"\caption{" + caption + r"}\label{" + label + r"}\\", r"\toprule",
                header + r" \\", r"\midrule", r"\endfirsthead", r"\toprule", header + r" \\", r"\midrule", r"\endhead",
                r"\bottomrule", r"\endfoot"]
        body += [r + r" \\" for r in rows]
        body += [r"\end{longtable}"]
        return "\n".join(body) + "\n"
    body = [r"\begin{" + env + "}[t]", r"\centering", r"\caption{" + caption + "}", r"\label{" + label + "}",
            r"\begin{tabular}{" + cols + "}", r"\toprule", header + r" \\", r"\midrule"]
    body += [r + r" \\" for r in rows]
    body += [r"\bottomrule", r"\end{tabular}", r"\end{" + env + "}"]
    return "\n".join(body) + "\n"


def seeds_of(df: pd.DataFrame, configs) -> str:
    n = sorted(set(int(v) for v in df[df.config.isin(configs)].n_seeds))
    return ", ".join(map(str, n))



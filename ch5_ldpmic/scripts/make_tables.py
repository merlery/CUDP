def _tab_selection(out: Path, name: str, metric: str, label: str, what: str):
    rows, notes = [], []
    ncol = len(SEL_EPS_GRID) + 1
    for key, meta in SEL_DATASETS.items():
        ds, pre = meta["dataset"], meta["prefix"]
        df = load_final(ds)
        nodp = cell(df, ds, meta["nodp"], None)
        rows.append((r"\midrule" + "\n" if rows else "") + r"\multicolumn{" + str(ncol) + r"}{l}{\textit{" + meta["name"]
                    + f"; no DP (main sweep): {pm(nodp[metric + '_mean'], nodp[metric + '_std'])}" + "}}")
        for suf, title in SEL_ROWS:
            if suf not in meta["rows"]:     # not recorded for this dataset by design (D39)
                continue
            cells = []
            for e in SEL_EPS_GRID:
                r = cell(df, ds, f"{pre}_{suf}", e)
                cells.append(pm(r[metric + "_mean"], r[metric + "_std"]) + (f" ({int(r.n_diverged)}d)" if r.n_diverged > 0 else ""))
            rows.append(title + " & " + " & ".join(cells))
        notes.append(f"{meta['name']}: {seeds_of(df, [f'{pre}_{suf}' for suf, _ in SEL_ROWS if suf in meta['rows']])} seeds")
    caption = (f"Selection experiment: final test {what} (mean $\\pm$ std over seeds) of the one-shot record release "
               "with all features (iso), with a random $k$-subset, and with the private top-$k$ MI selection "
               "(fixed-grid MI, analytic sensitivity, secure-aggregation release, uniform shares on the selected set), "
               "its non-private oracle, and local DP-SGD, at $\\varepsilon \\in \\{20, 50, 100, 200\\}$ ($\\delta = 10^{-5}$); "
               "``$k$d'' marks $k$ diverged seeds.  Seeds: " + "; ".join(notes) + ".")
    header = r"method & " + " & ".join(f"$\\varepsilon={fmt_eps(e)}$" for e in SEL_EPS_GRID)
    write(out, name, table("l" + "r" * len(SEL_EPS_GRID), header, rows, caption, label, env="table*"))



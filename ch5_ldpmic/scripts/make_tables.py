def tab_exposure_channels(out: Path, eps_list=(50.0, 100.0, 200.0), attr="sex", dataset="adult", partition="group",
                          arms=EXPOSURE_ARMS, name="tab_exposure_channels", label="tab:exposure-channels", title="Adult (occupation)"):
    """Exposure study (D46-D49): utility and attacker balanced accuracy through the proxy, direct and all channels."""
    att = load_csv("attribute_inference.csv")
    att = att[(att.dataset == dataset) & (att.partition == partition) & (att.attribute == attr)]
    fin = load_final(dataset)
    rows, n_seeds = [], set()
    for e in eps_list:
        rows.append((r"\midrule" + "\n" if rows else "") + r"\multicolumn{6}{l}{\textit{" + f"{title}, attribute {attr}, $\\varepsilon = {fmt_eps(e)}$" + "}}")
        for cfg, lab in arms:
            r = cell(fin, dataset, cfg, e)
            a = att[(att.config == cfg) & ((att.eps - e).abs() < 1e-9)]
            if len(a) != 1:
                raise MissingCell(f"missing attack cell: dataset={dataset}, config={cfg}, attribute={attr}, eps={e}")
            a = a.iloc[0]; n_seeds.add(int(a.n_seeds))
            direct = "--" if pd.isna(a.direct_balanced_accuracy_mean) else f"{a.direct_balanced_accuracy_mean:.3f}"
            rows.append(f"{lab} & {r.accuracy_mean:.3f} & {r.balanced_accuracy_mean:.3f} & {a.balanced_accuracy_mean:.3f} & {direct} & {a.all_balanced_accuracy_mean:.3f}")
    caption = (f"Exposure of the {attr} attribute on {title}: final test accuracy and balanced accuracy of the model trained on the release, "
               "and the balanced accuracy of a logistic-regression attacker (trained on the released records of half the clients, evaluated on the "
               "other half) that uses the other released coordinates (proxy), only the attribute's own released coordinates (direct; ``--'' when the "
               "attribute is not released), or all released coordinates (all). The cap bounds the share of the sensitive columns at $1/d$; exclusion "
               "removes them from the selected set. Mean over " + ", ".join(map(str, sorted(n_seeds))) + " seeds; the same $(\\varepsilon, 10^{-5})$ "
               "guarantee holds for every row.")
    header = r"release & accuracy & bal.\ acc. & proxy & direct & all"
    write(out, name, table("lrrrrr", header, rows, caption, label, env="table*"))



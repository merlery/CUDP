import numpy as np
import yaml

from src import dialogue as DLG
from src import infer as INF
from src import uldp as U
from src.run import ROOT

CFG = yaml.safe_load(open(ROOT / "config.yaml"))
H, L, K = DLG.contrast_table(CFG)


def test_vote_sum_stays_one_after_every_update():
    rng = np.random.default_rng(0)
    N, S = 500, 7
    pair = rng.integers(0, 3, (N, S))
    con = rng.integers(0, 3, (N, S))
    ans = rng.integers(0, 2, (N, S)).astype(np.int8)
    used = rng.random((N, S)) < 0.8
    for s in range(1, S + 1):
        u = used.copy()
        u[:, s:] = False
        w = INF.vote_accumulate(pair, con, ans, u, K)
        assert np.allclose(w.sum(1), 1.0)
    p = INF.project(INF.vote_accumulate(pair, con, ans, used, K))
    assert (p >= 0).all() and np.allclose(p.sum(1), 1.0)


def test_vote_example():
    # LP wins both LP-LA prompts (strong, medium), CR wins the others
    d = dict(pair=np.array([[0, 0, 1, 1, 2, 2]]), contrast=np.array([[0, 1, 0, 1, 0, 1]]),
             answer=np.array([[1, 1, 0, 0, 0, 0]], np.int8), used=np.ones((1, 6), bool))
    w = INF.vote_accumulate(d["pair"], d["contrast"], d["answer"], d["used"], K)
    tot = 3 * 1.0 + 3 * 0.75
    assert np.allclose(w, [[1 / 3 + 1.75 / tot - 1.75 / tot, 1 / 3 - 1.75 / tot - 1.75 / tot, 1 / 3 + 3.5 / tot]])
    assert np.allclose(INF.vote(d, K).sum(), 1.0)


def test_bayes_recovers_privacy_share():
    """200 answers generated by exactly the analyst's response model (tau = 0.1, no misspecification),
    over the PrivAgent-6 prompt types: the posterior mean is within 0.05 of the true privacy share."""
    w_true = np.array([[0.45, 0.35, 0.20]])
    rng = np.random.default_rng(11)
    base = DLG.prompt_set(CFG, "pa6")
    reps = np.resize(np.arange(6), 200)
    pair, con = base[reps, 0][None, :], base[reps, 1][None, :]
    ans = np.zeros((1, 200), np.int8)
    for s in range(200):
        q, c = pair[0, s], con[0, s]
        p = 1 / (1 + np.exp(-(w_true[0, DLG.PAIRS[q][0]] - w_true[0, DLG.PAIRS[q][1]]) * (H[c] - L[c]) / 0.1))
        ans[0, s] = rng.random() < p
    d = dict(pair=pair, contrast=con, answer=ans, used=np.ones((1, 200), bool))
    draws = np.random.default_rng(5).dirichlet([1, 1, 1], size=20000)
    est = INF.bayes(d, H, L, draws, 0.1)
    assert abs(U.privacy_share(est)[0] - U.privacy_share(w_true)[0]) < 0.05


def test_bayes_no_answers_is_prior_mean():
    d = dict(pair=np.zeros((2, 3), int), contrast=np.zeros((2, 3), int), answer=np.zeros((2, 3), np.int8),
             used=np.zeros((2, 3), bool))
    draws = np.random.default_rng(6).dirichlet([1, 1, 1], size=20000)
    est = INF.bayes(d, H, L, draws, 0.1)
    assert np.allclose(est, draws.mean(0))
